    super.init // expected_error{{no exact matches in reference to initializer}}
    super.init() // expected_error{{'super.init' cannot be called outside of an initializer}}
    super.init(0) // expected_error{{'super.init' cannot be called outside of an initializer}} // expected_error {{missing argument label 'x:' in call}}
    super[0]        // expected_warning {{subscript is accessed but result is unused}}
    super
      .bar()
  }

  func bad_super_1() {
    super.$0 // expected_error{{expected identifier or 'init'}}
  }
}

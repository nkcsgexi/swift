  var foo: Int
  func bar() {}

  init() {} // expected_note {{found this candidate}}
  init(x: Int) {} // expected_note {{found this candidate}}

  subscript(x: Int) -> Int {
    get {}
    set {}
  }
}

class D : B {
  override init() {
    super.init()
    super.init(42)
    // expected_error@-1 {{missing argument label 'x:' in call}}
  }

  override init(x:Int) {
    let _: () -> B = super.init // expected_error {{cannot reference 'super.init' initializer chain as function value}}
  }

  convenience init(y:Int) {
    let _: () -> D = self.init // expected_error {{cannot reference 'self.init' initializer delegation as function value}}
  }

  init(z: Int) {
    super
      .init(x: z)
  }

  func super_calls() {
    super.foo        // expected_warning {{property is accessed but result is unused}}
    super.foo.bar    // expected_error {{value of type 'Int' has no member 'bar'}}
    super.bar        // expected_error {{function is unused}}
    super.bar()

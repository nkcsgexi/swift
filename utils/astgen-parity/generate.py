def ifconfig_lines(source):
    """Returns (lines inside #if clauses, #if/#elseif/#else/#endif lines)."""
    inside, directives, depth = set(), set(), 0
    for i, line in enumerate((SWIFT_SRC / source).read_bytes().split(b'\n'), 1):
        s = line.lstrip()
        if re.match(rb'#(if|elseif|else|endif)\b', s):
            directives.add(i)
            if s.startswith(b'#if'):
                depth += 1
            elif s.startswith(b'#endif'):
                depth = max(0, depth - 1)
        elif depth:
            inside.add(i)
    return inside, directives


def line_info(source):
    inside, directives = ifconfig_lines(source)
    return inside, directives, neutralized_body(source).count(b'\n')


def diag_tags(d, inside, directives, body_lines):
    tags = []
    if d['line'] == 0:
        tags.append('unknown_loc')
    elif d['line'] > body_lines:
        tags.append('at_eof')
    if d['line'] in inside:
        tags.append('in_ifconfig_clause')
    if d['line'] in directives:
        tags.append('ifconfig_condition')
    return tags


def gap_category(cfg, legacy, new):
    """passing, crash, ifconfig, a GAP_TYPES entry, or mixed.

    Tests where ASTGen crashes are filed under 'crash'. Otherwise a failing
    test is filed under the gap type behind more than half of its failing
    diagnostics; gaps on or inside #if lines count as 'ifconfig'.
    """
    if cfg['status'] == 'passing':
        return 'passing'
    if cfg['new_harvest_error'] == 'crash':
        return 'crash'
    inside, directives, body_lines = line_info(cfg['source'])
    counts = collections.Counter()
    for cat, l, n in classify(legacy, new):
        if cat not in GAP_TYPES:
            continue
        tags = diag_tags(l or n, inside, directives, body_lines)
        ifconfig = {'in_ifconfig_clause', 'ifconfig_condition'} & set(tags)
        counts['ifconfig' if ifconfig else cat] += 1
    if counts:
        top, n = counts.most_common(1)[0]
        if 2 * n > sum(counts.values()):
            return top
    return 'mixed'


def classify(legacy, new):
    """Pairs diagnostics; returns list of (category, legacy_diag, new_diag)."""
    rows, lrest, nrest = [], list(legacy), list(new)
    passes = [
        ('exact', lambda d: (d['line'], d['col'], d['kind'])),
        ('wrong-column', lambda d: (d['line'], d['kind'])),
        ('wrong-severity', lambda d: (d['line'], d['col'])),
    ]
    for name, key in passes:
        pool = collections.defaultdict(list)
        for d in nrest:
            pool[key(d)].append(d)
        unmatched = []
        for d in lrest:
            if not pool[key(d)]:
                unmatched.append(d)
                continue
            n = pool[key(d)].pop(0)
            nrest.remove(n)
            if name == 'exact':
                name_ = 'matched' if d['message'] == n['message'] \
                    else 'message-differs'
                rows.append((name_, d, n))
            else:
                rows.append((name, d, n))
        lrest = unmatched
    rows += [('missing', d, None) for d in lrest]
    rows += [('extra', None, n) for n in nrest]
    return rows


def write_report(report_dir, configs, skips, legacy, new):
    out = pathlib.Path(report_dir)
    out.mkdir(parents=True, exist_ok=True)
    totals, missing_ids = collections.Counter(), collections.Counter()
    tag_totals = collections.Counter()
    with open(out / 'per-diag.csv', 'w', newline='') as f, \
            open(out / 'per-file.csv', 'w', newline='') as g:
        dw, fw = csv.writer(f), csv.writer(g)
        dw.writerow(['output', 'category', 'line', 'col', 'legacy_kind',
                     'legacy_id', 'legacy_message', 'new_kind', 'new_message',
                     'tags'])
        cats = ['matched', 'message-differs', 'wrong-column',
                'wrong-severity', 'missing', 'extra']
        fw.writerow(['output', 'status', 'category'] + cats +
                    ['new_harvest_error'])
        for c in configs:
            inside, directives, body_lines = line_info(c['source'])
            per = collections.Counter()
            for cat, l, n in classify(legacy[c['output']], new[c['output']]):
                d = l or n
                tags = diag_tags(d, inside, directives, body_lines)
                per[cat] += 1
                totals[cat] += 1
                if cat != 'matched':
                    tag_totals.update(tags)
                if cat == 'missing':
                    missing_ids[l['id'] or '?'] += 1
                dw.writerow([c['output'], cat, d['line'], d['col'],
                             l and l['kind'], l and l['id'],
                             l and l['message'], n and n['kind'],
                             n and n['message'], ' '.join(tags)])
            fw.writerow([c['output'], c['status'], c['category']] +
                        [per[k] for k in cats] +
                        [c['new_harvest_error']])

    status = collections.Counter(c['status'] for c in configs)
    reasons = collections.Counter(re.sub(r':.*', '', s['reason'])
                                  for s in skips)
    md = ['# ASTGen diagnostic parity: %s' % CORPUS, '',
          '| | count |', '|---|---|',
          '| generated tests | %d |' % len(configs),
          '| xfail (not at parity) | %d |' % status['xfail'],
          '| passing (regression guards) | %d |' % status['passing'],
          '| skipped configs/files | %d |' % len(skips), '',
          '## Tests by directory (gap type behind most failures)', '',
          '| directory | tests |', '|---|---|'] + [
          '| %s/ | %d |' % kv for kv in collections.Counter(
              c['category'] for c in configs).most_common()] + ['',
          '## Diagnostics by category', '', '| category | count |',
          '|---|---|']
    md += ['| %s | %d |' % kv for kv in sorted(totals.items())]
    md += ['', '## Tags on non-matched diagnostics', '', '| tag | count |',
           '|---|---|']
    md += ['| %s | %d |' % kv for kv in tag_totals.most_common()]
    md += ['', '## Top missing legacy diagnostics', '', '| id | count |',
           '|---|---|']
    md += ['| %s | %d |' % kv for kv in missing_ids.most_common(30)]
    md += ['', '## Skip reasons', '', '| reason | count |', '|---|---|']
    md += ['| %s | %d |' % kv for kv in reasons.most_common()]
    (out / 'SUMMARY.md').write_text('\n'.join(md) + '\n')



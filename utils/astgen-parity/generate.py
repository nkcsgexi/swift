def generate(args):
    configs, skips = plan()
    if args.filter:
        configs = [c for c in configs if args.filter in c['source']]
    suite_dir = SWIFT_SRC / SUITE / 'Parse'
    if suite_dir.exists() and not args.filter:
        shutil.rmtree(suite_dir)

    # Harvest the legacy oracle; repeat until the appended block has exactly
    # as many lines as the skeleton's padding, so EOF diagnostics are stable.
    size = {c['output']: block_size(c, []) for c in configs}
    legacy, pending = {}, list(configs)
    for _ in range(4):
        if not pending:
            break
        for c in pending:
            write_test(c, STATUS_PENDING, size[c['output']], [])
        results = run_lit(args, 'harvest-legacy', [c['output'] for c in pending])
        still = []
        for c in pending:
            diags, err = harvest(c, *results.get(c['output'], ('MISSING', '')))
            if err:
                skips.append({'source': c['source'], 'output': c['output'],
                              'reason': 'legacy harvest: ' + err})
                continue
            want = block_size(c, expectation_lines(diags))
            if want == size[c['output']]:
                legacy[c['output']] = diags
            else:
                size[c['output']] = want
                still.append(c)
        pending = still
    for c in pending:
        skips.append({'source': c['source'], 'output': c['output'],
                      'reason': 'oracle unstable'})
    configs = [c for c in configs if c['output'] in legacy]
    for c in pending + [s for s in skips if 'output' in s]:
        out = c['output']
        if out not in legacy and (SWIFT_SRC / out).exists():
            (SWIFT_SRC / out).unlink()

    # ASTGen diagnostics at the same layout, for the report.
    results = run_lit(args, 'harvest-new', [c['output'] for c in configs])
    new = {}
    for c in configs:
        diags, err = harvest(c, *results.get(c['output'], ('MISSING', '')))
        new[c['output']] = diags if diags is not None else []
        c['new_harvest_error'] = err or ''

    for c in configs:
        write_test(c, STATUS_PENDING, size[c['output']],
                   expectation_lines(legacy[c['output']]))

    # The expectations must encode the legacy parser exactly.
    results = run_lit(args, 'legacy', [c['output'] for c in configs])
    bad = [c for c in configs if results.get(c['output'], ('',))[0] != 'PASS']
    for c in bad:
        skips.append({'source': c['source'], 'output': c['output'],
                      'reason': 'legacy self-check: %s' %
                      results.get(c['output'], ('MISSING',))[0]})
        (SWIFT_SRC / c['output']).unlink()
    configs = [c for c in configs if c not in bad]

    results = run_lit(args, '', [c['output'] for c in configs])
    for c in configs:
        code = results.get(c['output'], ('MISSING',))[0]
        c['status'] = {'PASS': 'passing', 'FAIL': 'xfail'}.get(code, code)
        set_status(c, STATUS_XFAIL if code == 'FAIL' else STATUS_PASSING)

    staging = '%s/Parse/%s/' % (SUITE, STAGING)
    for c in configs:
        old = c['output']
        c['category'] = gap_category(c, legacy[old], new[old])
        rel = old[len(staging):]
        for stale in glob.glob(str(SWIFT_SRC / SUITE / 'Parse' / '*' / rel)):
            if not stale.startswith(str(SWIFT_SRC / staging)):
                pathlib.Path(stale).unlink()
        c['output'] = '%s/Parse/%s/%s' % (SUITE, c['category'], rel)
        dest = SWIFT_SRC / c['output']
        dest.parent.mkdir(parents=True, exist_ok=True)
        (SWIFT_SRC / old).rename(dest)
        legacy[c['output']], new[c['output']] = legacy.pop(old), new.pop(old)
    shutil.rmtree(SWIFT_SRC / staging, ignore_errors=True)

    results = run_lit(args, '', [c['output'] for c in configs])
    codes = collections.Counter(results.get(c['output'], ('MISSING',))[0]
                                for c in configs)

    manifest = {'configs': configs, 'skipped': skips}
    (TOOL_DIR / 'manifest.json').write_text(
        json.dumps(manifest, indent=1, sort_keys=True) + '\n')
    write_report(args.report_dir, configs, skips, legacy, new)
    print('confirm run:', dict(codes))
    print('generated %d tests (%d xfail, %d passing), skipped %d' % (
        len(configs), sum(c['status'] == 'xfail' for c in configs),
        sum(c['status'] == 'passing' for c in configs), len(skips)))
    print('by category:', dict(collections.Counter(
        c['category'] for c in configs).most_common()))
    return codes



#!/usr/bin/env python3
"""Generate the ASTGen diagnostic-parity lit suite.

For every frontend configuration of every test in test/Parse, this records the
diagnostics the *legacy* C++ parser emits (the oracle) and writes a lit test
under test/ASTGenParity/Parse that runs the same source through ASTGen
(-enable-experimental-feature ParserASTGen) with -verify, expecting exactly
those diagnostics.  Expectations check location and severity only
(`expected-error@L:C {{}}`); message wording is compared in the report.

Tests where ASTGen is not yet at parity are marked `// XFAIL: *`, so fixing a
gap makes the test XPASS and forces the marker to be removed (a ratchet).

  generate.py plan                          # enumerate configs, write manifest
  generate.py generate --build-dir DIR      # harvest, emit tests, report
  generate.py check --build-dir DIR         # regenerate and diff (drift)
  generate.py check --structural            # bodies still match test/Parse

DIR is a build-script build dir, e.g. ../build/Ninja-RelWithDebInfoAssert.
"""

import argparse
import collections
import csv
import glob
import json
import pathlib
import re
import shlex
import shutil
import subprocess
import sys
import tempfile

SWIFT_SRC = pathlib.Path(__file__).resolve().parents[2]
CORPUS = 'test/Parse'
SUITE = 'test/ASTGenParity'
TOOL_DIR = SWIFT_SRC / 'utils' / 'astgen-parity'

HEADER = (b'// ---- ASTGen parity: generated by '
          b'utils/astgen-parity/generate.py; DO NOT EDIT ----')
PAD = b'// astgen-parity-pad'
STATUS_PENDING = b'// parity: pending'
STATUS_PASSING = b'// parity: passing'
STATUS_XFAIL = b'// XFAIL: *'
# Fixed last line, so diagnostics reported at the end of the final line (e.g.
# unterminated block comments) don't depend on the block's content.
TRAILER = b'// ---- end ASTGen parity ----'
STAGING = 'pending'
# Sub-directory per test: the gap type behind most of its failures.
GAP_TYPES = ['missing', 'extra', 'wrong-column', 'wrong-severity']

# Same-length replacements that make the copied body inert for lit and the
# verifier while keeping every line and column of the original source.
NEUTRALIZE = [
    (b'expected-', b'expected_'),
    (b'RUN:', b'RUN;'),
    (b'REQUIRES:', b'REQUIRES;'),
    (b'UNSUPPORTED:', b'UNSUPPORTED;'),
    (b'XFAIL:', b'XFAIL;'),
    (b'ALLOW_RETRIES:', b'ALLOW_RETRIES;'),
    (b'DEFINE:', b'DEFINE;'),  # also covers REDEFINE:
    (b'END.', b'END,'),
]
EXPANSION_MARKER_RE = re.compile(rb'(//\s*)#(?=[A-Za-z0-9_-]+@\d)')

DRIVERS = {
    '%target-typecheck-verify-swift': '%target-swift-frontend',
    '%target-swift-frontend': '%target-swift-frontend',
    '%swift': '%swift',
}
KEEP_FLAG = {
    '-parse-stdlib', '-parse-as-library', '-disable-objc-interop',
    '-enable-objc-interop', '-disable-implicit-concurrency-module-import',
    '-disable-implicit-string-processing-module-import',
    '-enable-library-evolution', '-playground', '-enable-bare-slash-regex',
    '-enable-experimental-static-assert', '-enable-experimental-move-only',
    '-enable-experimental-concurrency', '-enable-experimental-com-interop',
    '-warnings-as-errors', '-suppress-warnings',
}
KEEP_VALUE = {
    '-swift-version': 1, '-language-mode': 1, '-D': 1, '-target': 1,
    '-module-name': 1, '-enable-experimental-feature': 1,
    '-enable-upcoming-feature': 1, '-disable-experimental-feature': 1,
    '-disable-upcoming-feature': 1, '-module-can-import': 1,
    '-module-can-import-version': 3,
    '-define-enabled-availability-domain': 1,
    '-define-disabled-availability-domain': 1,
    '-define-dynamic-availability-domain': 1, '-define-availability': 1,
}
KEEP_JOINED = {'-strict-concurrency', '-com-interop-model'}
# Actions, verifier knobs, outputs, and import/SDK setup (-parse loads no
# modules).  Body-skipping flags are dropped because the legacy parser never
# parses skipped bodies in -parse mode while ASTGen always does.
DROP_FLAG = {
    '-typecheck', '-parse', '-verify', '-verify-ignore-unrelated',
    '-verify-ignore-unknown', '-verify-ignore-macro-note', '-dump-parse',
    '-dump-ast', '-emit-module', '-c', '-debug-diagnostic-names', '-emit-sil',
    '-emit-silgen', '-emit-ir', '-disable-availability-checking',
    '-enable-source-import', '-experimental-skip-all-function-bodies',
    '-experimental-skip-non-inlinable-function-bodies',
    '-disable-objc-attr-requires-foundation-module',
}
DROP_VALUE = {
    '-I', '-F', '-sdk', '-module-cache-path', '-o', '-emit-module-path',
    '-emit-module-interface-path', '-user-module-version',
    '-import-objc-header', '-serialize-diagnostics-path',
    '-verify-additional-prefix', '-diagnostic-style',
}
DROP_JOINED = {'-diagnostic-style'}
# Changing these would make the comparison meaningless.
PARSER_FEATURES = {'ParserASTGen', 'ParserValidation', 'ParserRoundTrip'}
SKIP_FLAG = {
    '-debugger-support': 'debugger support makes ASTGen fall back to legacy',
}

KIND_ORDER = {'error': 0, 'warning': 1, 'note': 2, 'remark': 3}
DIAG_RE = re.compile(r'^(\S.*?):(\d+):(\d+): error: unexpected '
                     r'(error|warning|note|remark) produced: (.*)$')
UNKNOWN_RE = re.compile(r'^(?:<unknown>:0: )?error: unexpected '
                        r'(error|warning|note|remark) produced: (.*)$')
ELSEWHERE_RE = re.compile(r'diagnostic produced elsewhere|'
                          r'is not parsed for \'expected\' statements')
NAME_RE = re.compile(r'^(.*) \[([A-Za-z0-9_]+)\]$')
CRASH_RE = re.compile(r'Stack dump:|PLEASE submit a bug report')
LIT_STDERR_PREFIX_RE = re.compile(r'^# \| ?')


# ---------------------------------------------------------------------------
# Corpus enumeration
# ---------------------------------------------------------------------------

def known_features():
    text = (SWIFT_SRC / 'include/swift/Basic/Features.def').read_text()
    return set(re.findall(r'^\s*[A-Z_]*FEATURE[A-Z_]*\(\s*(\w+)', text, re.M))


def exceptional_files():
    text = (SWIFT_SRC / 'test/Misc/verify-swift-feature-testing.test-sh'
            ).read_text()
    block = text.split('EXCEPTIONAL_FILES', 1)[1].split(']', 1)[0]
    return set(re.findall(r'pathlib\.Path\("([^"]+)"\)', block))


def run_lines(text):
    runs, cur = [], ''
    for line in text.splitlines():
        m = re.search(r'RUN:(.*)$', line)
        if not m:
            continue
        t = m.group(1).rstrip()
        if t.endswith('\\'):
            cur += t[:-1] + ' '
            continue
        runs.append((cur + t).strip())
        cur = ''
    return runs


def directive_values(text, keyword):
    values = []
    for m in re.finditer(r'\b%s:(.*)$' % keyword, text, re.M):
        values += [v.strip() for v in m.group(1).split(',') if v.strip()]
    return values


def parse_frontend_segment(segment, features):
    """Returns (driver, flags, enabled_features) or a skip-reason string."""
    try:
        toks = shlex.split(segment)
    except ValueError as e:
        return 'unparsable RUN line: %s' % e
    idx = next((i for i, t in enumerate(toks) if t in DRIVERS), None)
    if idx is None:
        return None
    driver = DRIVERS[toks[idx]]
    # %target-typecheck-verify-swift already expands to include %s.
    inputs = 1 if toks[idx] == '%target-typecheck-verify-swift' else 0
    flags, enabled = [], []
    it = iter(toks[idx + 1:])
    for t in it:
        if t in ('>', '2>', '>>', '&>'):
            next(it, None)
            continue
        if t.startswith(('>', '2>', '&>')):
            continue
        if t == '%s':
            inputs += 1
            continue
        if not t.startswith('-'):
            return 'extra input or argument: %s' % t
        name, _, joined = t.partition('=')
        if t in SKIP_FLAG:
            return SKIP_FLAG[t]
        if t in KEEP_FLAG:
            flags.append(t)
        elif t in DROP_FLAG:
            pass
        elif t in KEEP_VALUE:
            vals = [next(it, '') for _ in range(KEEP_VALUE[t])]
            if t.endswith('-feature'):
                feature = vals[0].split(':')[0]
                if feature in PARSER_FEATURES:
                    continue
                if feature not in features:
                    return 'unknown feature: %s' % feature
                if t.startswith('-enable'):
                    enabled.append(feature)
            if any(re.search(r'%t(?![\w-])', v) for v in vals):
                return 'depends on %%t artifacts: %s' % t
            flags.append(t)
            flags += vals
        elif t in DROP_VALUE:
            next(it, None)
        elif t == '-primary-file':
            if next(it, None) == '%s':
                inputs += 1
        elif t.startswith('-D') and len(t) > 2:
            flags.append(t)
        elif joined and name in KEEP_JOINED:
            flags.append(t)
        elif joined and name in DROP_JOINED:
            pass
        else:
            return 'unsupported flag: %s' % t
    if inputs != 1:
        return 'expected exactly one %%s input, got %d' % inputs
    return driver, flags, enabled


def plan():
    """Enumerates configurations. Returns (configs, skips)."""
    features = known_features()
    exceptional = exceptional_files()
    configs, skips = [], []
    for path in sorted((SWIFT_SRC / CORPUS).rglob('*.swift')):
        rel = path.relative_to(SWIFT_SRC).as_posix()
        if 'Inputs' in path.parts:
            continue
        if rel in exceptional:
            skips.append({'source': rel, 'reason': 'feature-checker exception'})
            continue
        if b'\0' in path.read_bytes():
            # git grep treats it as binary, which breaks
            # test/Misc/verify-swift-feature-testing.test-sh.
            skips.append({'source': rel, 'reason': 'contains NUL bytes'})
            continue
        text = path.read_bytes().decode('utf-8', 'replace')
        runs = run_lines(text)
        if any('split-file' in r for r in runs):
            skips.append({'source': rel, 'reason': 'split-file test'})
            continue
        requires = [v for v in directive_values(text, 'REQUIRES')
                    if not v.startswith('swift_feature_')]
        unsupported = directive_values(text, 'UNSUPPORTED')
        seen = []
        for run in runs:
            for segment in re.split(r'\s(?:\|\||\||&&|;)\s', run):
                if '%target-swift-frontend(' in segment:
                    skips.append({'source': rel, 'run': run,
                                  'reason': 'mock-sdk frontend'})
                    continue
                result = parse_frontend_segment(segment, features)
                if result is None:
                    continue
                if isinstance(result, str):
                    skips.append({'source': rel, 'run': run, 'reason': result})
                    continue
                key = (result[0], tuple(result[1]))
                if key not in [(c[0], tuple(c[1])) for c in seen]:
                    seen.append(result)
        if not seen:
            if not any(s['source'] == rel for s in skips):
                skips.append({'source': rel,
                              'reason': 'no frontend RUN line on %s'})
            continue
        for i, (driver, flags, enabled) in enumerate(seen):
            out = rel[len(CORPUS) + 1:]
            if len(seen) > 1:
                out = out[:-len('.swift')] + '.cfg%d.swift' % (i + 1)
            configs.append({
                'source': rel,
                'output': '%s/Parse/%s/%s' % (SUITE, STAGING, out),
                'driver': driver,
                'flags': flags,
                'features': sorted(set(enabled) | {'ParserASTGen'}),
                'requires': sorted(set(requires)),
                'unsupported': sorted(set(unsupported)),
            })
    return configs, skips



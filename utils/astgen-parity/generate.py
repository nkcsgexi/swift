def lit_command(build_dir):
    lit = SWIFT_SRC.parent / 'llvm-project/llvm/utils/lit/lit.py'
    sites = sorted(glob.glob(str(pathlib.Path(build_dir) /
                                 'swift-macosx-*/test-macosx-*/lit.site.cfg')))
    if not sites:
        sys.exit('no swift test lit.site.cfg under %s' % build_dir)
    return [sys.executable, str(lit), '--param',
            'swift_site_config=%s' % sites[0]]


def run_lit(args, mode, outputs):
    """Runs lit over the given tests; returns {output path: (code, text)}."""
    if not outputs:
        return {}
    with tempfile.TemporaryDirectory() as tmp:
        result = pathlib.Path(tmp) / 'lit.json'
        cmd = lit_command(args.build_dir) + [
            '-j', str(args.jobs), '-q', '--param',
            'astgen_parity_mode=%s' % mode, '--param', 'output_limit=%d' % 2**30,
            '-o', str(result)] + [str(SWIFT_SRC / o) for o in outputs]
        subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
        if not result.exists():
            sys.exit('lit produced no results for mode %r' % mode)
        tests = json.loads(result.read_text())['tests']
    by_output = {}
    for t in tests:
        rel = 'test/' + t['name'].split(' :: ', 1)[1]
        by_output[rel] = (t['code'], t.get('output', ''))
    return by_output


def harvest(cfg, code, text):
    """Returns (diags, error) parsed from a verifier run with no expectations."""
    if code in ('UNSUPPORTED', 'UNRESOLVED'):
        return None, 'lit %s' % code
    if CRASH_RE.search(text):
        return None, 'crash'
    if 'data was truncated' in text:
        return None, 'lit output truncated'
    if ELSEWHERE_RE.search(text):
        return None, 'diagnostic in another buffer'
    target = str(SWIFT_SRC / cfg['output'])
    diags = []
    for line in text.splitlines():
        line = LIT_STDERR_PREFIX_RE.sub('', line)
        m = DIAG_RE.match(line)
        if m:
            if m.group(1) != target:
                return None, 'diagnostic in another file: %s' % m.group(1)
            loc = (int(m.group(2)), int(m.group(3)))
            kind, msg = m.group(4), m.group(5)
        else:
            m = UNKNOWN_RE.match(line)
            if not m:
                continue
            loc, kind, msg = (0, 0), m.group(1), m.group(2)
        n = NAME_RE.match(msg)
        msg, diag_id = (n.group(1), n.group(2)) if n else (msg, '')
        diags.append({'line': loc[0], 'col': loc[1], 'kind': kind,
                      'message': msg, 'id': diag_id})
    if code == 'FAIL' and not diags:
        return None, 'failed without verifier output'
    return diags, None



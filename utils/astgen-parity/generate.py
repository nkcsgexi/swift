# Test file construction
# ---------------------------------------------------------------------------

def neutralized_body(source):
    body = (SWIFT_SRC / source).read_bytes()
    for old, new in NEUTRALIZE:
        body = body.replace(old, new)
    body = EXPANSION_MARKER_RE.sub(rb'\1_', body)
    if body and not body.endswith(b'\n'):
        body += b'\n'
    return body


def fixed_lines(cfg):
    run = ' '.join([cfg['driver'], '-parse', '-verify',
                    '-disable-objc-attr-requires-foundation-module'] +
                   [shlex.quote(f) if f[:1] != '%' else f
                    for f in cfg['flags']] +
                   ['%s', '-enable-experimental-feature ParserASTGen',
                    '%{astgen-parity-override}'])
    lines = [HEADER, b'// SOURCE; ' + cfg['source'].encode(),
             b'// RUN: ' + run.encode(), b'// REQUIRES: swift_swift_parser']
    lines += [b'// REQUIRES: swift_feature_' + f.encode()
              for f in cfg['features']]
    lines += [b'// REQUIRES: ' + r.encode() for r in cfg['requires']
              if r != 'swift_swift_parser']
    lines += [b'// UNSUPPORTED: ' + u.encode() for u in cfg['unsupported']]
    return lines


def expectation_lines(diags):
    groups = collections.OrderedDict()
    for d in sorted(diags, key=lambda d: (d['line'], d['col'],
                                          KIND_ORDER[d['kind']])):
        groups.setdefault((d['line'], d['col'], d['kind']), []).append(d)
    lines = []
    for (line, col, kind), ds in groups.items():
        loc = '<unknown>' if line == 0 else '%d:%d' % (line, col)
        count = ' %d' % len(ds) if len(ds) > 1 else ''
        ids = ','.join(sorted({d['id'] for d in ds if d['id']}))
        tail = ' // ' + ids if ids else ''
        lines.append(('// expected-%s@%s%s {{}}%s' %
                      (kind, loc, count, tail)).encode())
    return lines


def block_size(cfg, expectations):
    return len(fixed_lines(cfg)) + 1 + len(expectations) + 1


def write_test(cfg, status, size, expectations):
    lines = fixed_lines(cfg) + [status] + expectations
    assert len(lines) + 1 <= size
    lines += [PAD] * (size - len(lines) - 1) + [TRAILER]
    path = SWIFT_SRC / cfg['output']
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(neutralized_body(cfg['source']) +
                     b'\n'.join(lines) + b'\n')


def set_status(cfg, status):
    path = SWIFT_SRC / cfg['output']
    data = path.read_bytes()
    for old in (STATUS_PENDING, STATUS_PASSING, STATUS_XFAIL):
        marker = b'\n' + old + b'\n'
        if marker in data.split(HEADER, 1)[1]:
            head, tail = data.split(HEADER, 1)
            data = head + HEADER + tail.replace(marker,
                                                b'\n' + status + b'\n', 1)
            break
    path.write_bytes(data)



def check_structural():
    manifest = json.loads((TOOL_DIR / 'manifest.json').read_text())
    bad = 0
    for c in manifest['configs']:
        data = (SWIFT_SRC / c['output']).read_bytes()
        body = data.split(HEADER + b'\n', 1)[0]
        if body != neutralized_body(c['source']):
            print('body drift: %s (from %s)' % (c['output'], c['source']))
            bad += 1
    return bad


def check_full(args):
    suite_dir = SWIFT_SRC / SUITE / 'Parse'
    with tempfile.TemporaryDirectory() as tmp:
        saved = pathlib.Path(tmp) / 'Parse'
        shutil.copytree(suite_dir, saved)
        shutil.copy(TOOL_DIR / 'manifest.json', pathlib.Path(tmp) / 'm.json')
        args.filter, args.report_dir = None, str(pathlib.Path(tmp) / 'report')
        generate(args)
        diff = subprocess.run(['diff', '-r', '-q', str(saved), str(suite_dir)],
                              capture_output=True, text=True).stdout
        shutil.rmtree(suite_dir)
        shutil.copytree(saved, suite_dir)
        shutil.copy(pathlib.Path(tmp) / 'm.json', TOOL_DIR / 'manifest.json')
    print(diff or 'no drift')
    return 1 if diff else 0


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawTextHelpFormatter)
    sub = p.add_subparsers(dest='cmd', required=True)
    sub.add_parser('plan')
    for name in ('generate', 'check'):
        s = sub.add_parser(name)
        s.add_argument('--build-dir')
        s.add_argument('--jobs', type=int, default=8)
        s.add_argument('--report-dir', default=str(TOOL_DIR / 'report'))
        if name == 'generate':
            s.add_argument('--filter', help='only sources containing this')
        else:
            s.add_argument('--structural', action='store_true')
    args = p.parse_args()

    if args.cmd == 'plan':
        configs, skips = plan()
        reasons = collections.Counter(re.sub(r':.*', '', s['reason'])
                                      for s in skips)
        print('%d configs from %d files; %d skips' % (
            len(configs), len({c['source'] for c in configs}), len(skips)))
        for r, n in reasons.most_common():
            print('  %4d  %s' % (n, r))
        return 0
    if args.cmd == 'check' and args.structural:
        return 1 if check_structural() else 0
    if not args.build_dir:
        p.error('--build-dir is required')
    if args.cmd == 'generate':
        codes = generate(args)
        return 0 if set(codes) <= {'PASS', 'XFAIL'} else 1
    return check_full(args)


if __name__ == '__main__':
    sys.exit(main())
